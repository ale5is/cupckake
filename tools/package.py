#!/usr/bin/env python3
import hashlib
import json
import sys
import tomllib
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "mixins" / "simple-voice-chat"
TARGET = ROOT / "target"
GAME = "26.3"
ALLOWED_TEXT = ("README", "LICENSE", "LICENCE", "COPYING", "NOTICE")


def inside(path, folder):
    try:
        path.relative_to(folder)
        return True
    except ValueError:
        return False


def opus_source_bundle(crate_root):
    vendor = crate_root / "vendor"
    if not vendor.is_dir():
        raise SystemExit("Missing vendored Opus sources in the repository")
    lines = [
        "// Generated by tools/package.py. Source files are hex-encoded so the",
        "// official .hnmod source-only format can carry Opus C files safely.",
    ]
    for path in sorted(p for p in vendor.rglob("*") if p.is_file()):
        rel = path.relative_to(vendor).as_posix()
        lines.append(f"// FILE: {rel}")
        lines.append(f"// HEX: {path.read_bytes().hex()}")
    return ("\n".join(lines) + "\n").encode()


def main():
    compatibility = json.loads((ROOT / "compatibility.json").read_text(encoding="utf-8"))
    mixin_path = BUNDLE / "horizon-mixin.toml"
    mixin = tomllib.loads(mixin_path.read_text(encoding="utf-8"))
    mod = mixin["mod"]
    mod_id = mod["id"]
    version = mod["version"]

    if not (BUNDLE / "runtime.rs").is_file():
        raise SystemExit("Missing runtime.rs")
    if not (mod_id and mod_id.replace("_", "").isalnum() and mod_id == mod_id.lower()):
        raise SystemExit("Native mod id must match [a-z0-9_]{1,64}")
    if mixin.get("compatibility", {}).get("horizon_revision") != compatibility["horizon_revision"]:
        raise SystemExit("horizon-mixin.toml and compatibility.json pin different Horizon revisions")
    if compatibility["game"] != GAME:
        raise SystemExit(f"This bundle targets Minecraft {GAME}, not {compatibility['game']}")
    api_root = BUNDLE / mixin.get("api", {}).get("path", "api")
    svc_root = BUNDLE / "crates" / "svc_client"
    if not (api_root / "Cargo.toml").is_file() or not (api_root / "build.rs").is_file():
        raise SystemExit("Missing native trait-mod API Cargo.toml or build.rs")
    if not (svc_root / "vendor" / "src" / "opus.c").is_file():
        raise SystemExit("Missing vendored Opus source in svc_client")

    manifest = {
        "schema": 1,
        "id": mod_id,
        "version": version,
        "game": GAME,
        "horizon": compatibility["horizon_revision"],
        "mixins": compatibility["horizon_mixins_revision"],
        "hooks": compatibility["hooks"],
    }
    files = {
        "horizon-native.json": (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    }
    data_dirs = [Path("data"), Path("crates/svc_client/data")]
    for path in sorted(BUNDLE.rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(BUNDLE)
        allowed = path.suffix in (".rs", ".toml")
        allowed = allowed or any(inside(relative, folder) for folder in data_dirs)
        if allowed:
            files[f"mixins/{mod_id}/{relative.as_posix()}"] = path.read_bytes()

    generated = opus_source_bundle(svc_root)
    files[f"mixins/{mod_id}/crates/svc_client/opus_sources.rs"] = generated

    license_path = ROOT / "LICENSE"
    if license_path.is_file():
        files[f"mixins/{mod_id}/LICENSE"] = license_path.read_bytes()

    required = [
        f"mixins/{mod_id}/horizon-mixin.toml",
        f"mixins/{mod_id}/runtime.rs",
        f"mixins/{mod_id}/api/Cargo.toml",
        f"mixins/{mod_id}/api/build.rs",
        f"mixins/{mod_id}/crates/svc_client/opus_sources.rs",
    ]
    missing = [name for name in required if name not in files]
    if missing:
        raise SystemExit("Package is missing required sources: " + ", ".join(missing))

    TARGET.mkdir(parents=True, exist_ok=True)
    output = TARGET / f"{mod_id}-{version}.hnmod"
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, content in sorted(files.items()):
            info = zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            info.create_system = 3
            archive.writestr(info, content)

    digest = hashlib.sha256(output.read_bytes()).hexdigest()
    with zipfile.ZipFile(output) as archive:
        names = set(archive.namelist())
        if not set(required).issubset(names) or "horizon-native.json" not in names:
            raise SystemExit("Archive verification failed")
        embedded = json.loads(archive.read("horizon-native.json"))
        if embedded != manifest:
            raise SystemExit("Embedded horizon-native.json does not match compatibility metadata")
        forbidden = [n for n in names if n.endswith((".c", ".h", ".inc", ".S", ".s", ".in"))]
        if forbidden:
            raise SystemExit("Forbidden native source extensions in hnmod: " + ", ".join(forbidden[:5]))

    print(json.dumps({
        "file": str(output),
        "size": output.stat().st_size,
        "sha256": digest,
        "entries": len(files),
        "id": mod_id,
        "version": version,
        "game": GAME,
        "format": ".hnmod",
        "opus_sources": "hex-embedded in opus_sources.rs",
    }, indent=2))


if __name__ == "__main__":
    main()
